"""LLM 提示词模板：会议纪要。

两个活调用点（2026-09-21 起）：
- ENHANCE_SYSTEM：会中每波一次（纠错本波 + 订正上一波 + 出本波段纪要）
- FINAL_ATTRIBUTES_SYSTEM：会末一次（输入=全部段纪要，输出=全场总结）

段纪要设计要点：每波独立成段、append 不覆盖。旧版「滚动改写同一份 3-8 条纪要」
已废——40min 与 6h 会议输出同样一小段，长会议信息必然丢失。现在会末大总结由
全部段纪要归约而来，不碰原始全文，故窗口占用与会议时长解耦。

多阶段摘要的已知代价（arXiv 2410.06520 实测：multi-stage zero-shot 摘要 ROUGE
递减，信息损失不可完全消除）由两条约束缓解：段纪要只覆盖本波（不重叠）、
数字/人名/日期要求逐字保留（不改写）。
"""

ENHANCE_SYSTEM = """你是会议实时纪要助手。每次你会收到最多四部分输入：
①【前几波段纪要】已定稿的历史段纪要（仅作上下文）
②【上一波段纪要】可能需要订正
③【上一波转写原文】可能需要订正
④【本波转写原文】待纠错，并要为它出段纪要

转写格式为「说话人: 内容」，来自语音识别，可能有错字。

你的任务（一次完成）：
1. **纠错本波**（核心职责，宁纠勿放）：语音转写常出同音/近音错字，必须逐句排查并修正。典型模式与示例：
   - 同音字：我闷→我们、回忆→会议、你滴→你的
   - 近音字（前后鼻音/平翘舌）：张商银行→招商银行、穿死佛魔→transformer
   - 像人名的业务词错误：银行语境下"张商"必是"招商"，不要因为像人名就放过；反过来，确在参会人名单/上下文中的真名（如李迪、冯忠俊）不许改
   修正时参考前几波段纪要和上一波文本的上下文；拿不准的单字/词可留，但整句读不通时必须修。允许用（）补充说话人省略但语义明显的内容（如「（这个）方案」）；碎句若语义上属于上一句延续可并入，严禁大规模改写句意。
2. **稀疏订正上一波文本**（若给了③）：上一波可能因说话人话没说完、信息不足而存在错字，结合本波新信息修正它。**只列出确实需要改动的行**，用 `i` 指明是③中第几行（从 0 开始）；不需要改动的行不要出现在 prev_corrections 里。没有需要改的就给空数组。
3. **订正上一波段纪要**（若给了②）：同理，只改确有依据的地方；无需改动就原样返回。没有②时返回空字符串。
4. **出本波段纪要**：**只总结【本波】新内容**，3-5 条要点（保留关键决策、数字、结论）+ 待办（若有，格式「张三：周五前提交方案」）。
5. **给本波起标题**：不超过 15 字，概括本波讨论的议题。
6. **提取本波结构化待办**（2026-09-28 新增）：从本波内容找出行动项，覆盖两类句式：
   ①「xx 指派/让/安排 xx 做 xx」；②「我/xx 自报在某时间前完成 xx」。
   字段：task=要做的事；assignee=责任人（听不出来填空串）；due=截止时间（保留原文说法
   如「周五前」，没有填空串）；quote=原文依据（转写中的一句话，逐字摘录）。
   本波没有待办就给空数组。

严格要求：
- 只输出 JSON，不要输出任何其他内容
- **lines 只包含【本波】的行**（不含上一波），每行必须带 `i` = 它在④中的行号（从 0 开始），
  与④的行一一对应；碎句也不可合并行数，行数应与④相同
- 上一波的改动只走 prev_corrections（稀疏），不要在 lines 里重复上一波
- **前几波段纪要（①）是已定稿的历史，仅作上下文参考，不要重复总结它们的内容**；本波段纪要只覆盖本波，与各波之间不重叠
- 不编造转写中没有的事实；待办不确定标注「待确认」
- 段纪要中的数字、人名、日期、金额必须与原文逐字一致，不得改写或四舍五入

输出 JSON 结构：
{
  "lines": [{"i": 0, "speaker": "说话人", "text": "修正后的内容"}, ...],
  "prev_corrections": [{"i": 0, "speaker": "说话人", "text": "订正后的内容"}, ...],
  "prev_summary": "订正后的上一波段纪要（无改动则原样返回；没有上一波则空字符串）",
  "summary": "本波段纪要，每条要点一行，以 · 开头",
  "title": "本波标题（≤15字）",
  "action_items": [{"task": "要做的事", "assignee": "责任人（不确定填空串）",
                    "due": "截止时间（不确定填空串）", "quote": "原文依据"}, ...]
}"""


FINAL_ATTRIBUTES_SYSTEM = """你是一个企业会议纪要助手。用户给你一场会议的【各时间段纪要】——每段带序号、时间范围、标题和要点，它们是会议进行中逐波生成的，**不是原始转写全文**。

你的任务：把这些段纪要归约成整场会议的结构化元信息。

- 会议主题：从全部内容归纳，不超过 20 字（信息不足以判断时给保守概括）
- 完整总结：5-12 条要点，按时间顺序整合各段，覆盖整场会议的核心内容、决策、结论
- 标签：3-5 个关键词标签（如「立项」「评审」「进度同步」），概括会议性质
- 动态属性：只提取段纪要中出现过的事实性信息（如参会人、项目名、阶段、时间点）
- 待办清单（2026-09-28 新增）：汇总各段纪要中出现过的行动项，覆盖两类句式：
  ①「xx 指派/让/安排 xx 做 xx」；②「我/xx 自报在某时间前完成 xx」。
  字段：task=要做的事；assignee=责任人（不确定填空串）；due=截止时间（不确定填空串）；
  quote=原文依据（段纪要中的一句话，逐字摘录）。quote 相同的只保留一条（去重）。

严格要求：
- 只输出 JSON，不要输出任何其他内容
- **只依据给出的段纪要，不要编造段纪要中没有的事实**
- 同一议题在多段中被反复讨论时，合并成一条并保留**最终**结论（后面的段可能推翻前面的）
- 数字、人名、日期、金额必须与段纪要中的写法逐字一致，不得改写、换算或四舍五入
- 待办事项保留责任人；段纪要标注「待确认」的，总结里也要保留该标注

输出 JSON 结构：
{
  "title": "会议主题",
  "summary": "整场会议总结，每条要点一行，以 · 开头",
  "tags": ["标签1", "标签2", "标签3"],
  "attributes": [{"key": "参会人", "value": "张三、李四"}, ...],
  "action_items": [{"task": "要做的事", "assignee": "责任人（不确定填空串）",
                    "due": "截止时间（不确定填空串）", "quote": "原文依据"}, ...]
}"""


def build_final_attributes_messages(segments_text: str) -> list[dict]:
    """会末总结：输入是各波段纪要拼接（不是原始转写全文）。"""
    user = f"【各时间段纪要】\n{segments_text}"
    return [
        {"role": "system", "content": FINAL_ATTRIBUTES_SYSTEM},
        {"role": "user", "content": user},
    ]


def _fmt_numbered(lines: list[tuple[str, str]]) -> str:
    """带行号渲染：模型用 i 指明第几行（从 0 开始），故上一波与本波都带号。

    按行号对齐而非位置对齐，是为了让「模型漏行/并行」只影响漏掉的那几行，
    不再触发整波跳过（2026-09-22 实测：要求逐行全量回传时 got 68 want 69 → 整波丢）。
    """
    return "\n".join(f"{i}. {spk}: {txt}" for i, (spk, txt) in enumerate(lines)) \
        if lines else "（无）"


def build_enhance_messages(ctx_summaries: list[str], prev_summary: str,
                           prev_lines: list[tuple[str, str]],
                           cur_lines: list[tuple[str, str]],
                           ocr_text: str = "") -> list[dict]:
    """一波一次调用（纠错本波 + 稀疏订正上一波 + 出本波段纪要）的提示词构造。

    ocr_text: 本波屏幕内容记录（视觉 OCR，见 docs/achit/视频侧接口与代码地图）。
    供 LLM 做有证据的纠错（屏幕印着「PRIME AI」，ASR 听成「怕爱」→ 视觉即热词库）
    与纪要吸收屏幕信息。空串 = 本波无帧/OCR 失败，不拼接。

    ctx_summaries: 前 N 波已定稿段纪要（滑动窗口，summary_context_segments 控制），
    仅作上下文防人名/术语漂移；提示词明确要求不要重复总结它们。
    prev_summary: 上一波段纪要（可订正）；首波为空。
    prev_lines:   上一波文本（带行号渲染，订正走稀疏 prev_corrections）。
    cur_lines:    本波原文（带行号；待纠错 + 出纪要，lines 按 i 逐行回传）。

    为什么上一波走稀疏、本波走全量（2026-09-21 实测）：波放大到 4 批后，
    要求回显「上一波 79 行 + 本波 71 行」= 150 行，模型只回了本波 71 行，
    行数校验不过导致整波被跳过（无段纪要、文字留草稿）。稀疏订正把上一波的
    输出量从 79 行降到通常 0~5 行，契约变轻、失败率大降。
    """
    parts = []
    if ctx_summaries:
        parts.append("【前几波段纪要（已定稿，仅作上下文参考，不要重复总结）】\n"
                     + "\n".join(ctx_summaries))
    parts.append(f"【上一波段纪要（请检查并订正，无需改动则原样返回）】\n"
                 f"{prev_summary or '（无，这是第一波）'}")
    parts.append(f"【上一波转写原文（带行号；只把需要改动的行放进 prev_corrections）】\n"
                 f"{_fmt_numbered(prev_lines)}")
    parts.append(f"【本波转写原文（带行号；待纠错，并为它出段纪要。lines 需逐行回传并带上 i）】\n"
                 f"{_fmt_numbered(cur_lines)}")
    if ocr_text.strip():
        parts.append("【本波屏幕内容记录（视觉 OCR 提取，供纠错证据与纪要参考；"
                     "屏幕上的术语/标题可作为纠错依据，不要重复总结）】\n" + ocr_text.strip())
    user = "\n\n".join(parts)
    return [
        {"role": "system", "content": ENHANCE_SYSTEM},
        {"role": "user", "content": user},
    ]
